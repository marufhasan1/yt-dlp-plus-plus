import { existsSync, mkdirSync, mkdtempSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { afterAll, beforeAll, describe, expect, it, vi } from 'vitest'
import type { ConversionJob } from '@shared/types/converter'
import { DEFAULT_SETTINGS } from '@shared/validation/settings'
import { locateFfmpegToolchain, systemSearchDirs } from '../../electron/services/engines/engine-locator'
import { parseProbe, probeArgs } from '../../electron/services/media/conversion-plan'
import { ConversionService } from '../../electron/services/media/conversion.service'
import { silentLogger } from '../../electron/utils/logger'
import { runProcess } from '../../electron/utils/process'

/*
 * Runs the real converter with real FFmpeg/FFprobe (found on PATH), on media
 * generated by FFmpeg itself. Skipped where FFmpeg is not installed.
 */

let ffmpeg: string | null = null
let ffprobe: string | null = null
let dir: string

async function generate(args: string[]): Promise<void> {
  const result = await runProcess(ffmpeg!, ['-hide_banner', '-loglevel', 'error', '-y', ...args], { timeoutMs: 60_000 })
  if (result.exitCode !== 0) throw new Error(result.stderr)
}

beforeAll(async () => {
  const found = await locateFfmpegToolchain(
    { managed: join(tmpdir(), 'none'), bundled: null, system: systemSearchDirs(process.env['PATH'], process.platform) },
    process.platform
  )
  if (found.ffmpeg?.source === 'system' && found.ffprobe) {
    ffmpeg = found.ffmpeg.path
    ffprobe = found.ffprobe.path
  }
  if (!ffmpeg) return
  dir = mkdtempSync(join(tmpdir(), 'mediaflow-convert-'))
  mkdirSync(join(dir, 'in'))
  mkdirSync(join(dir, 'out'))
  await generate(['-f', 'lavfi', '-i', 'sine=frequency=440:duration=6', '-ac', '2', '-metadata', 'title=Tone Ünïcode', '-metadata', 'artist=MediaFlow', join(dir, 'in', 'Tést fïle ñ 🎵.wav')])
  await generate(['-f', 'lavfi', '-i', 'testsrc=duration=4:size=320x240:rate=25', '-f', 'lavfi', '-i', 'sine=duration=4', '-c:v', 'libx264', '-c:a', 'aac', '-shortest', join(dir, 'in', 'clip.mp4')])
  await generate(['-f', 'lavfi', '-i', 'color=c=blue:size=200x200:duration=1', '-frames:v', '1', join(dir, 'in', 'cover.png')])
  await generate(['-i', join(dir, 'in', 'Tést fïle ñ 🎵.wav'), '-i', join(dir, 'in', 'cover.png'), '-map', '0:a', '-map', '1:v', '-c:a', 'libmp3lame', '-b:a', '128k', '-c:v', 'png', '-disposition:v', 'attached_pic', '-id3v2_version', '3', join(dir, 'in', 'with cover.mp3')])
  await generate(['-f', 'lavfi', '-i', 'sine=duration=600', join(dir, 'in', 'long.wav')])
  writeFileSync(join(dir, 'in', 'broken.mp3'), 'not audio at all')
}, 120_000)

afterAll(() => {
  if (dir) rmSync(dir, { recursive: true, force: true })
})

function converter(files: string[]): ConversionService {
  return new ConversionService({
    toolchain: async () => ({ ffmpeg: ffmpeg!, ffprobe: ffprobe! }),
    acquire: () => () => {},
    run: runProcess,
    dialogs: { pickFiles: async () => files, pickFolder: async () => join(dir, 'out') },
    settings: () => ({ ...DEFAULT_SETTINGS, downloadDirectory: join(dir, 'out') }),
    defaultDownloadDir: join(dir, 'out'),
    logger: silentLogger
  })
}

async function settled(service: ConversionService, ids: string[]): Promise<ConversionJob[]> {
  await vi.waitFor(
    () => {
      const jobs = service.list().filter((j) => ids.includes(j.id))
      expect(jobs.every((j) => ['completed', 'failed', 'cancelled'].includes(j.status))).toBe(true)
    },
    { timeout: 90_000, interval: 200 }
  )
  return service.list().filter((j) => ids.includes(j.id))
}

async function probeFile(path: string) {
  const result = await runProcess(ffprobe!, probeArgs(path))
  return parseProbe(JSON.parse(result.stdout))
}

describe.runIf(process.env['MEDIAFLOW_SKIP_FFMPEG'] !== '1')('ConversionService with real FFmpeg', () => {
  it('inspects picked files, including damaged ones', async (context) => {
    if (!ffmpeg) context.skip()
    const service = converter([join(dir, 'in', 'Tést fïle ñ 🎵.wav'), join(dir, 'in', 'clip.mp4'), join(dir, 'in', 'broken.mp3')])
    const inputs = await service.pickFiles()
    expect(inputs.map((i) => i.name)).toEqual(['Tést fïle ñ 🎵.wav', 'clip.mp4', 'broken.mp3'])
    expect(inputs[0]).toMatchObject({ durationSeconds: 6, error: null, source: { codec: 'pcm_s16le', title: 'Tone Ünïcode' } })
    expect(inputs[1]?.source).toMatchObject({ codec: 'aac', hasVideo: true })
    expect(inputs[2]).toMatchObject({ source: null, error: 'This file is damaged or is not a supported audio or video file.' })
    await expect(service.start({ inputs: [inputs[2]!.token], format: 'mp3', quality: '192', destination: { kind: 'downloads' } })).rejects.toMatchObject({ code: 'VALIDATION_FAILED' })
  }, 60_000)

  it('converts to every format, one at a time, and verifies the results', async (context) => {
    if (!ffmpeg) context.skip()
    const service = converter([join(dir, 'in', 'Tést fïle ñ 🎵.wav')])
    const [input] = await service.pickFiles()
    const seen = new Set<string>()
    let concurrent = 0
    service.onChanged(() => {
      const running = service.list().filter((j) => j.status === 'converting').length
      concurrent = Math.max(concurrent, running)
      for (const j of service.list()) seen.add(j.status)
    })

    const ids: string[] = []
    for (const format of ['mp3', 'm4a', 'opus', 'flac', 'wav'] as const) {
      const [job] = await service.start({ inputs: [input!.token], format, quality: format === 'mp3' ? '192' : 'best', destination: { kind: 'downloads' } })
      ids.push(job!.id)
    }
    const jobs = await settled(service, ids)
    expect(jobs.map((j) => [j.format, j.status, j.error])).toEqual(
      expect.arrayContaining([
        ['mp3', 'completed', null],
        ['m4a', 'completed', null],
        ['opus', 'completed', null],
        ['flac', 'completed', null],
        ['wav', 'completed', null]
      ])
    )
    expect(concurrent).toBe(1)

    const expected = { mp3: 'mp3', m4a: 'aac', opus: 'opus', flac: 'flac', wav: 'pcm_s16le' } as const
    for (const job of jobs) {
      expect(job.outputPath).toMatch(new RegExp(`Tést fïle ñ 🎵\\.${job.format}$`))
      const out = await probeFile(job.outputPath!)
      expect(out.source?.codec).toBe(expected[job.format])
      expect(out.durationSeconds).toBeCloseTo(6, 0)
    }
    const mp3 = await probeFile(jobs.find((j) => j.format === 'mp3')!.outputPath!)
    expect(mp3.source).toMatchObject({ title: 'Tone Ünïcode', artist: 'MediaFlow' })
    // No temporary files are left behind.
    expect(readdirSync(join(dir, 'out')).some((name) => name.includes('.mediaflow-'))).toBe(false)
  }, 120_000)

  it('extracts audio from video, keeps cover art, and never overwrites', async (context) => {
    if (!ffmpeg) context.skip()
    const service = converter([join(dir, 'in', 'clip.mp4'), join(dir, 'in', 'with cover.mp3')])
    const [clip, covered] = await service.pickFiles()
    const first = await service.start({ inputs: [clip!.token, covered!.token], format: 'm4a', quality: '128', destination: { kind: 'source' } })
    const second = await service.start({ inputs: [clip!.token], format: 'm4a', quality: '128', destination: { kind: 'source' } })
    const jobs = await settled(service, [...first, ...second].map((j) => j.id))
    expect(jobs.every((j) => j.status === 'completed')).toBe(true)

    const clipOutputs = jobs.filter((j) => j.inputName === 'clip.mp4').map((j) => j.outputPath).sort()
    expect(clipOutputs).toEqual([join(dir, 'in', 'clip (1).m4a'), join(dir, 'in', 'clip.m4a')].sort())
    expect((await probeFile(join(dir, 'in', 'clip.m4a'))).source?.hasVideo).toBe(false)
    const coverOut = await probeFile(jobs.find((j) => j.inputName === 'with cover.mp3')!.outputPath!)
    expect(coverOut.source?.hasCover).toBe(true)
  }, 120_000)

  it('cancels a running conversion and removes the partial file', async (context) => {
    if (!ffmpeg) context.skip()
    const service = converter([join(dir, 'in', 'long.wav')])
    const [input] = await service.pickFiles()
    const [job] = await service.start({ inputs: [input!.token], format: 'flac', quality: 'best', destination: { kind: 'custom', token: (await service.chooseFolder())!.token } })
    await vi.waitFor(() => expect(service.list().find((j) => j.id === job!.id)?.status).toBe('converting'), { timeout: 20_000 })
    await service.cancel(job!.id)
    const [done] = await settled(service, [job!.id])
    expect(done?.status).toBe('cancelled')
    expect(readdirSync(join(dir, 'out')).filter((n) => n.startsWith('long'))).toEqual([])
    expect(existsSync(join(dir, 'in', 'long.wav'))).toBe(true)
  }, 120_000)

  it('rejects tokens it did not issue', async (context) => {
    if (!ffmpeg) context.skip()
    const service = converter([])
    await expect(service.start({ inputs: ['00000000-0000-4000-8000-000000000000'], format: 'mp3', quality: '192', destination: { kind: 'downloads' } })).rejects.toMatchObject({ code: 'NOT_FOUND' })
    await expect(service.start({ inputs: [], format: 'mp3', quality: '192', destination: { kind: 'custom', token: '00000000-0000-4000-8000-000000000000' } })).rejects.toBeDefined()
  })
})
